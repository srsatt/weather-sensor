export function initialLanguage() {
  const stored = localStorage.getItem("weather-language");
  if (stored === "en" || stored === "ru") return stored;
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export function translator(language) {
  const strings = STRINGS[language] ?? STRINGS.en;
  return (key, values = {}) => {
    const value = key.split(".").reduce((current, part) => current?.[part], strings);
    if (typeof value !== "string") return key;
    return value.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
  };
}
